// Последњи успешно прочитани одговор, по рути.
//
// Служи за кратке прекиде базе. Кад читање не успе, рута враћа оно што је
// последњи пут прочитала, уз ознаку да су подаци застарели, уместо да
// сруши цео екран. Јеловник се мења двапут месечно, па је застарео
// одговор готово увек и тачан.
//
// Ово живи у меморији процеса и нестаје при поновном покретању. То је
// свесно: трајни извор истине је база, а не сервер. Уређај који је већ
// отварао апликацију покривен је и својим кешом у прегледачу.

const MAX_KEYS = 60;
const store = new Map();

/** Памти успешан одговор. */
export function remember(key, data) {
  // Мапа чува редослед уписа, па најстарији улази испадају први.
  if (store.size >= MAX_KEYS && !store.has(key)) {
    store.delete(store.keys().next().value);
  }
  store.set(key, { data, at: new Date().toISOString() });
}

/** Враћа последњи запамћен одговор, или null. */
export function recall(key) {
  return store.get(key) ?? null;
}

export function size() {
  return store.size;
}
