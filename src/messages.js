/**
 * Бира текст на основу датума, тако да се порука не понавља кроз недељу.
 * Исти дан и исти оброк увек дају исти текст, што чини слање поновљивим.
 */
export function pickMessage(meal, isoDate) {
  const pool = POOLS[meal];
  const [y, m, d] = isoDate.split('-').map(Number);
  const index = (y * 372 + m * 31 + d) % pool.length;
  return pool[index];
}

